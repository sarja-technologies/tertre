#!/usr/bin/env python3
"""Generate src/glyph_data.rs: coverage templates for printable ASCII.

Each glyph is rasterised with DejaVu Sans Mono into a terminal-cell-shaped
canvas and box-filtered down to GW x GH samples.  The renderer matches
source-video patches against these templates (see src/render.rs).
"""
import sys
from PIL import Image, ImageDraw, ImageFont

GW, GH = 4, 8
FONT = sys.argv[1] if len(sys.argv) > 1 else "/usr/share/fonts/truetype/dejavu/DejaVuSansMono.ttf"
SIZE = 48
font = ImageFont.truetype(FONT, SIZE)
asc, desc = font.getmetrics()
cw = round(font.getlength("M"))
ch = asc + desc
# canvas multiple of the sample grid
W = (cw // GW + 1) * GW
H = (ch // GH + 1) * GH
rows = []
for code in range(32, 127):
    im = Image.new("L", (W, H), 0)
    ImageDraw.Draw(im).text(((W - cw) // 2, (H - ch) // 2), chr(code), font=font, fill=255)
    small = im.resize((GW, GH), Image.BOX)
    rows.append(list(small.getdata()))

out = []
out.append("// @generated by tools/gen_glyphs.py -- do not edit by hand.")
out.append(f"// Source font: {FONT.split('/')[-1]}; {GW}x{GH} coverage samples, 0..=255.")
out.append(f"pub const GW: usize = {GW};")
out.append(f"pub const GH: usize = {GH};")
out.append("pub const ASCII_COVERAGE: [[u8; GW * GH]; 95] = [")
for code, r in zip(range(32, 127), rows):
    c = chr(code)
    label = c if c not in "\\*/" else f"0x{code:02x}"
    out.append("    [" + ", ".join(str(v) for v in r) + f"], // {label}")
out.append("];")
open("src/glyph_data.rs", "w").write("\n".join(out) + "\n")
print("ok", W, H)
